import Foundation
import PDFKit
import Testing
@testable import Hisingen

struct VehicleReportBuilderTests {
    private let vin = "YV1ZB2345K1234567"
    private let registration = "ZX12ABC"
    private let generatedAt = Calendar.current.date(
        from: DateComponents(year: 2026, month: 11, day: 21, hour: 12)
    ) ?? Date()

    // MARK: - Text report

    @Test("The text report carries the title, meta rows and footer of the report menu")
    func textReportShape() {
        // Number formats follow the interface locale; pin it so "92.4%" is what every
        // machine renders, not just an English-region one.
        withPinnedInterfaceLanguage {
            let report = VehicleReportBuilder.textReport(input())

            #expect(report.contains("Vehicle Report"))
            #expect(report.contains("Data From:"))
            #expect(report.contains("Model: Polestar 2 2024"))
            #expect(report.contains("Architecture: Battery Electric"))
            #expect(report.contains("Charging: Not charging"))
            #expect(report.contains("Charge Target: 85%"))
            #expect(report.contains("Service Due:"))
            #expect(report.contains("Calculated SoH: 92.4%"))
            #expect(report.contains("Generated by Hisingen. Calculated values are estimates, not vehicle telemetry."))
        }
    }

    @Test("Screenshot privacy masks the VIN and drops registration, address and coordinates")
    func textReportRedacted() {
        let report = VehicleReportBuilder.textReport(input(redacted: true))

        #expect(!report.contains(vin))
        #expect(report.contains("VIN: " + String(repeating: "•", count: vin.count - 4) + vin.suffix(4)))
        #expect(!report.contains("Registration"))
        #expect(!report.contains("Parking Address"))
        #expect(!report.contains("Coordinates"))
        #expect(report.contains("Privacy: VIN, plate, and location redacted"))
    }

    @Test("Without screenshot privacy the identifiers and location are written out")
    func textReportUnredacted() {
        withPinnedInterfaceLanguage {
            let report = VehicleReportBuilder.textReport(input(redacted: false))

            #expect(report.contains("VIN: \(vin)"))
            #expect(report.contains("Registration: \(registration)"))
            #expect(report.contains("Parking Address: Sannegårdens Pir 4"))
            #expect(report.contains("Coordinates: 57.70890, 11.97460"))
            #expect(!report.contains("Privacy:"))
        }
    }

    @Test("A powertrain without electric range omits the charging rows entirely")
    func chargingRowsFollowThePowertrain() {
        var values = input()
        values.chargingStateName = nil
        let report = VehicleReportBuilder.textReport(values)

        #expect(!report.contains("Charging:"))
        #expect(!report.contains("Charge Target:"))
    }

    @Test("A stale charge target keeps the note the charging card shows")
    func chargeTargetNoteIsCarried() {
        var values = input()
        values.chargeTargetNote = "Last changed 2025-05-11"
        let report = VehicleReportBuilder.textReport(values)

        #expect(report.contains("Charge Target: 85% · Last changed 2025-05-11"))
    }

    @Test("Without a battery estimate the calculated rows stay absent")
    func noEstimateMeansNoSoHRows() {
        var values = input()
        values.batteryEstimate = nil
        let report = VehicleReportBuilder.textReport(values)

        #expect(!report.contains("Calculated SoH"))
        #expect(!report.contains("Calculation Method"))
    }

    // MARK: - PDF report

    @Test("The PDF is a readable document with at least one page")
    func pdfIsReadable() throws {
        let data = VehicleReportBuilder.pdfData(input())

        #expect(!data.isEmpty)
        #expect(String(decoding: data.prefix(5), as: UTF8.self) == "%PDF-")
        let document = try #require(PDFDocument(data: data))
        #expect(document.pageCount >= 1)
    }

    @Test("The PDF carries the report rows, so the share sheet shares what the text report says")
    func pdfTextMatchesTheReport() throws {
        let data = VehicleReportBuilder.pdfData(input())
        let text = try #require(PDFDocument(data: data)?.string ?? "")

        #expect(text.contains("Vehicle Report"))
        #expect(text.contains("Model: Polestar 2 2024"))
        #expect(text.contains("Architecture: Battery Electric"))
    }

    @Test("The PDF honours screenshot privacy the same way as the text report")
    func pdfRedactionBothWays() throws {
        let redacted = try #require(PDFDocument(data: VehicleReportBuilder.pdfData(input(redacted: true)))?.string ?? "")
        #expect(!redacted.contains(vin))
        #expect(redacted.contains("VIN: " + String(repeating: "•", count: vin.count - 4) + vin.suffix(4)))
        #expect(!redacted.contains(registration))
        #expect(!redacted.contains("Parking Address"))
        #expect(!redacted.contains("Coordinates"))

        let open = try #require(PDFDocument(data: VehicleReportBuilder.pdfData(input(redacted: false)))?.string ?? "")
        #expect(open.contains(vin))
        #expect(open.contains(registration))
        #expect(open.contains("Parking Address"))
    }

    @Test("The shared file name names the model and date, never the VIN")
    func pdfFileNameCarriesNoVIN() {
        let name = VehicleReportBuilder.pdfFileName(model: "Polestar 2", generatedAt: generatedAt)

        #expect(name == "Hisingen Report Polestar 2 2026-11-21.pdf")
        #expect(!name.contains(vin))
        #expect(VehicleReportBuilder.pdfFileName(model: nil, generatedAt: generatedAt)
            == "Hisingen Report Vehicle 2026-11-21.pdf")
        #expect(VehicleReportBuilder.pdfFileName(model: "Polestar/2", generatedAt: generatedAt)
            == "Hisingen Report Polestar 2 2026-11-21.pdf")
    }

    // MARK: - Fixtures

    private func input(redacted: Bool = false) -> VehicleReportInput {
        VehicleReportInput(
            modelName: "Polestar 2",
            modelYear: "2024",
            vin: vin,
            registrationNo: registration,
            internalVehicleIdentifier: "internal-123",
            powertrainName: "Battery Electric",
            chargingStateName: "Not charging",
            chargeTargetPercent: 85,
            chargeTargetNote: nil,
            odometerKm: 48_210,
            distanceUnit: .kilometers,
            batteryPercent: 64,
            rangeKm: 251,
            exteriorPaint: "Thunder",
            upholstery: "Charcoal",
            buildWeek: "2024-W12",
            pno34: "PNO-1",
            marketDelivery: "SE",
            softwareVersion: "1.2.3",
            serviceDueInDays: 120,
            inServiceDate: nil,
            factoryWarrantyValidUntil: nil,
            batteryEstimate: estimate(),
            parkingAddress: "Sannegårdens Pir 4",
            latitude: 57.7089,
            longitude: 11.9746,
            dataTimestamp: generatedAt.addingTimeInterval(-600),
            generatedAt: generatedAt,
            redacted: redacted
        )
    }

    private func estimate() -> BatteryHealthEstimate {
        BatteryHealthEstimate(
            stateOfHealthPercent: 92.4,
            rawStateOfHealthPercent: 92.4,
            degradationPercent: 7.6,
            estimatedUsableCapacityKwh: 59.1,
            referenceUsableCapacityKwh: 64,
            fullChargeRangeKm: 370,
            wltpReferenceRangeKm: 400,
            recordedAt: generatedAt,
            isRemembered: false,
            method: BatteryHealthEstimator.fullChargeRangeMethod
        )
    }
}
